/* The What's new page (#499): app/whats-new.html is generated from
   scripts/whats-new.json by scripts/whats-new.mjs, the way the chart pages are
   generated by scripts/charts.mjs. The pure parts are tested here with
   made-up entries; the last test is the one that fails `npm test` when the
   source changed and the page was not regenerated. */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { lacks } from './prose.js';
import { LIMIT, weeks, renderPage, pages } from '../scripts/whats-new.mjs';

const e = (date, text) => ({ date, text });

test('the page shows the newest 15 entries', () => {
  assert.equal(LIMIT, 15);
  const many = Array.from({ length: 20 }, (_, i) => e('2026-11-02', `Entry number ${i}.`));
  const html = renderPage(many);
  assert.equal((html.match(/<li>/g) || []).length, 15);
  assert.ok(html.includes('Entry number 14.'));
  assert.ok(lacks(html, 'Entry number 15.'));
});

test('weeks start on Monday: Sunday 1 Nov and Monday 2 Nov land in different weeks', () => {
  const w = weeks([
    e('2026-11-02', 'Monday one.'), e('2026-11-01', 'Sunday one.'),
    e('2026-10-26', 'Previous Monday.'), e('2026-10-25', 'Sunday before.'),
  ]);
  assert.deepEqual(w.map(x => x.heading), [
    'Week of 2 November 2026', 'Week of 26 October 2026', 'Week of 19 October 2026',
  ]);
  assert.deepEqual(w.map(x => x.entries.map(y => y.text)), [
    ['Monday one.'], ['Sunday one.', 'Previous Monday.'], ['Sunday before.'],
  ]);
});

test('a week is one <ul> under one heading, newest week first', () => {
  const html = renderPage([e('2026-11-02', 'A.'), e('2026-11-01', 'B.'), e('2026-10-27', 'C.')]);
  assert.equal((html.match(/<ul>/g) || []).length, 2);
  assert.ok(html.indexOf('Week of 2 November 2026') < html.indexOf('Week of 26 October 2026'));
  assert.match(html, /<h2>Week of 26 October 2026<\/h2>\s*<ul>\s*<li>B\.<\/li>\s*<li>C\.<\/li>\s*<\/ul>/);
});

test('entry text is escaped, not trusted as markup', () => {
  const html = renderPage([e('2026-11-02', 'Tom & Jerry <b>"quoted"</b> it\'s.')]);
  assert.ok(html.includes('Tom &amp; Jerry &lt;b&gt;&quot;quoted&quot;&lt;/b&gt; it\'s.'));
  assert.ok(!html.includes('<b>"quoted"'));
});

test('the head says what the page is, once, and is indexable', () => {
  const html = renderPage([e('2026-11-02', 'A.')]);
  assert.ok(html.includes("<title>What's new | Benchcard</title>"));
  assert.match(html, /<link rel="canonical" href="https:\/\/benchcard\.app\/whats-new">/);
  assert.ok(!/noindex/.test(html));
  assert.equal((html.match(/<h1>What's new<\/h1>/g) || []).length, 1);
  assert.match(html, /<a class="btn primary" href="\/">Open Benchcard<\/a>/);
  assert.match(html, /href="\/about"/);
});

test('app/whats-new.html is what scripts/whats-new.mjs renders from scripts/whats-new.json', () => {
  for (const [name, want] of pages()) {
    let cur = null;
    try { cur = readFileSync(new URL('../app/' + name, import.meta.url), 'utf8'); } catch {}
    assert.equal(cur, want, `app/${name} is missing or stale -- run: npm run whats-new`);
  }
  assert.equal(pages().size, 1);
});

test('the real entries have real dates, newest first, and no repeated text', () => {
  const list = JSON.parse(readFileSync(new URL('../scripts/whats-new.json', import.meta.url), 'utf8'));
  assert.ok(list.length > 0);
  for (const { date } of list) {
    assert.match(date, /^\d{4}-\d{2}-\d{2}$/);
    assert.equal(new Date(date + 'T00:00:00Z').toISOString().slice(0, 10), date, `${date} is not a real date`);
  }
  for (let i = 1; i < list.length; i++) {
    assert.ok(list[i].date <= list[i - 1].date, `${list[i].date} is listed after ${list[i - 1].date}; newest first`);
  }
  const texts = list.map(x => x.text);
  assert.equal(new Set(texts).size, texts.length, 'an entry text repeats');
});
